/**
 * Studio-generated media as Vault files. Generation writes the bytes to the
 * product's bucket and records an `asset` row with one `asset_version`; the
 * `generation` row that produced it names that version. Those rows are the
 * file: the Vault lists and reads generated media from them, never from KV.
 *
 * The product supplies its database, its three tables, its bucket, and which
 * generated assets the Vault shows (for example approved ones, or ones a person
 * saved). Transcripts are text and go to the Vault store itself.
 */
