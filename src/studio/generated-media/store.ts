const ASSET_VERSION_QUERY_BATCH_SIZE = 200

function metadataRecord(value: unknown): Record<string, unknown> {
  return value && typeof value === 'object' && !Array.isArray(value) ? value as Record<string, unknown> : {}
}

function stringValue(value: unknown): string | undefined {
  return typeof value === 'string' && value.trim() ? value.trim() : undefined
}

function numberValue(value: unknown): number | undefined {
  return typeof value === 'number' && Number.isFinite(value) ? value : undefined
}

/** Run an id-keyed query in slices so a wide `IN (...)` list never becomes one oversized bound-parameter set. */
async function inIdChunks<T>(ids: string[], query: (batch: string[]) => PromiseLike<T[]>): Promise<T[]> {
  const rows: T[] = []
  for (let index = 0; index < ids.length; index += ASSET_VERSION_QUERY_BATCH_SIZE) {
    rows.push(...await query(ids.slice(index, index + ASSET_VERSION_QUERY_BATCH_SIZE)))
  }
  return rows
}

/** Reads of generated media rows: the Vault walk, path reads, provider-job dedupe. */
function createGeneratedMediaQueries<Context>(config: GeneratedMediaStoreConfig<Context>) {
  const { db } = config
  const { assets, assetVersions, generations } = config.tables

  async function cleanupGeneratedAssetRecords(assetId: string, assetVersionId?: string): Promise<void> {
    if (assetVersionId) {
      await db.delete(assetVersions).where(eq(assetVersions.id, assetVersionId))
    }
    await db.delete(assets).where(eq(assets.id, assetId))
  }

  async function walkGeneratedMediaVaultEntries(workspaceId: string): Promise<GeneratedMediaVaultEntry[]> {
    const generationRows = await db
      .select()
      .from(generations)
      .where(and(
        eq(generations.workspaceId, workspaceId),
        inArray(generations.type, ['image', 'video', 'avatar', 'speech']),
      ))
      .orderBy(desc(generations.createdAt)) as unknown as GenerationRow[]

    const assetVersionIds = generationRows
      .map((generation) => stringValue(metadataRecord(generation.metadata).assetVersionId))
      .filter((id): id is string => Boolean(id))
    const uniqueAssetVersionIds = [...new Set(assetVersionIds)]
    if (uniqueAssetVersionIds.length === 0) return []

    const versionRows = await listGeneratedAssetVersionRows(workspaceId, uniqueAssetVersionIds, { visibleOnly: true })
    const versionById = new Map(versionRows.map((row) => [row.version.id, row]))
    const entries: GeneratedMediaVaultEntry[] = []

    for (const generation of generationRows) {
      const assetVersionId = stringValue(metadataRecord(generation.metadata).assetVersionId)
      if (!assetVersionId) continue
      const row = versionById.get(assetVersionId)
      if (!row) continue
      const entry = buildGeneratedMediaVaultEntry(workspaceId, generation, row)
      if (entry) entries.push(entry)
    }

    return entries
  }

  /** The Vault walk shows only visible assets; deletion resolves every asset. */
  async function listGeneratedAssetVersionRows(
    workspaceId: string,
    assetVersionIds: string[],
    opts: { visibleOnly: boolean },
  ): Promise<GeneratedAssetVersionRow[]> {
    return inIdChunks(assetVersionIds, (batch) => db
      .select({ version: assetVersions, asset: assets })
      .from(assetVersions)
      .innerJoin(assets, eq(assets.id, assetVersions.assetId))
      .where(and(
        eq(assetVersions.workspaceId, workspaceId),
        inArray(assetVersions.id, batch),
        ...(opts.visibleOnly ? [config.vaultVisibility.condition(assets)] : []),
      )) as unknown as PromiseLike<GeneratedAssetVersionRow[]>)
  }

  async function readGeneratedMediaVaultEntryByPath(
    workspaceId: string,
    path: string,
    opts: { visibleOnly: boolean },
  ): Promise<GeneratedMediaVaultEntry | null> {
    const [row] = await db
      .select({ version: assetVersions, asset: assets })
      .from(assetVersions)
      .innerJoin(assets, eq(assets.id, assetVersions.assetId))
      .where(and(
        eq(assetVersions.workspaceId, workspaceId),
        eq(assets.workspaceId, workspaceId),
        eq(assets.type, 'generated'),
        eq(assets.vaultPath, path),
        ...(opts.visibleOnly ? [config.vaultVisibility.condition(assets)] : []),
      ))
      .orderBy(desc(assetVersions.createdAt))
      .limit(1) as unknown as GeneratedAssetVersionRow[]
    if (!row) return null

    const versionMetadata = metadataRecord(row.version.metadata)
    const assetMetadata = metadataRecord(row.asset.metadata)
    const generationType = stringValue(versionMetadata.generationType) ?? stringValue(assetMetadata.generationType)
    if (!isGeneratedMediaType(generationType)) return null

    const [generation] = await db
      .select()
      .from(generations)
      .where(and(
        eq(generations.workspaceId, workspaceId),
        eq(generations.type, generationType),
        sql`json_extract(${generations.metadata}, '$.assetVersionId') = ${row.version.id}`,
      ))
      .orderBy(desc(generations.createdAt))
      .limit(1) as unknown as GenerationRow[]
    if (!generation) return null

    const entry = buildGeneratedMediaVaultEntry(workspaceId, generation, row)
    return entry?.path === path ? entry : null
  }

  async function findPersistedGeneratedMediaByProviderJob(input: {
    workspaceId: string
    generationType: GeneratedMediaType
    providerJobId: string
  }): Promise<PersistedGeneratedMedia | null> {
    const [row] = await db
      .select({ version: assetVersions, asset: assets })
      .from(assetVersions)
      .innerJoin(assets, eq(assets.id, assetVersions.assetId))
      .where(and(
        eq(assetVersions.workspaceId, input.workspaceId),
        eq(assets.workspaceId, input.workspaceId),
        eq(assets.type, 'generated'),
        sql`json_extract(${assetVersions.metadata}, '$.generationType') = ${input.generationType}`,
        sql`json_extract(${assetVersions.metadata}, '$.providerJobId') = ${input.providerJobId}`,
      ))
      .orderBy(desc(assetVersions.createdAt))
      .limit(1) as unknown as GeneratedAssetVersionRow[]
    if (!row) return null
    return persistedGeneratedMediaFromRow(input.workspaceId, row)
  }

  async function listGeneratedMediaVaultPaths(workspaceId: string): Promise<string[]> {
    const entries = await walkGeneratedMediaVaultEntries(workspaceId)
    return entries.map((entry) => entry.path)
  }

  /** Path plus recorded size and mime type of every generated media file the Vault shows. */
  async function listGeneratedMediaVaultEntries(workspaceId: string): Promise<Array<{
    path: string
    sizeBytes: number | null
    mimeType: string | null
  }>> {
    const entries = await walkGeneratedMediaVaultEntries(workspaceId)
    return entries.map((entry) => ({
      path: entry.path,
      sizeBytes: entry.file.metadata.sizeBytes ?? null,
      mimeType: entry.file.mimeType,
    }))
  }

  async function readGeneratedMediaVaultFile(workspaceId: string, path: string): Promise<GeneratedMediaVaultFile | null> {
    validateVaultFilePath(path)
    const entry = await readGeneratedMediaVaultEntryByPath(workspaceId, path, { visibleOnly: config.vaultVisibility.pathReads })
    return entry?.file ?? null
  }

  return {
    cleanupGeneratedAssetRecords, listGeneratedAssetVersionRows, readGeneratedMediaVaultEntryByPath,
    findPersistedGeneratedMediaByProviderJob, listGeneratedMediaVaultPaths, listGeneratedMediaVaultEntries, readGeneratedMediaVaultFile,
  }
}

type GeneratedMediaQueries = ReturnType<typeof createGeneratedMediaQueries>

/** Writes of generated media: stored bytes, provider results, transcripts. */
function createGeneratedMediaWrites<Context>(config: GeneratedMediaStoreConfig<Context>, queries: GeneratedMediaQueries) {
  const { db } = config
  const { assets, assetVersions } = config.tables
  const { cleanupGeneratedAssetRecords, findPersistedGeneratedMediaByProviderJob } = queries

  /**
   * Store generated bytes as a draft `generated` asset with version 1. A
   * failure after the asset row exists removes the rows again. `recheck` runs
   * before each write so a caller can stop a generation whose authority ended.
   */
  async function persistGeneratedMediaAsset(input: {
    context: Context
    workspaceId: string
    userId: string
    generationType: GeneratedMediaType
    prompt: string
    model: string | null
    outputPath: string | null | undefined
    bytes: Uint8Array
    mimeType: string
    extension?: string
    metadata?: Record<string, unknown>
    recheck?: () => Promise<void>
  }): Promise<PersistedGeneratedMedia> {
    if (input.bytes.byteLength === 0) throw new Error(`Generated ${generatedMediaLabel(input.generationType)} returned an empty file`)

    const bucket = config.bucket(input.context)
    if (!bucket) throw new Error(`Generated ${generatedMediaLabel(input.generationType)} storage is not configured for this deployment.`)

    const id = crypto.randomUUID()
    const extension = input.extension ?? extensionForGeneratedMimeType(input.generationType, input.mimeType)
    const fileName = `studio-${id}${extension}`
    const vaultPath = resolveGeneratedVaultPath({
      type: input.generationType,
      outputPath: input.outputPath,
      fileName,
    })
    const r2Key = `workspace/${input.workspaceId}/generated-media/${id}${extension}`
    const outputConfig = GENERATED_OUTPUT_CONFIG[input.generationType]
    const sizeBytes = input.bytes.byteLength
    const assetMetadata = {
      source: 'studio-generate',
      generationType: input.generationType,
      model: input.model,
      mimeType: input.mimeType,
      sizeBytes,
      vaultPath,
      ...input.metadata,
    }

    await input.recheck?.()
    const [asset] = await db
      .insert(assets)
      .values({
        workspaceId: input.workspaceId,
        title: input.prompt.slice(0, 120) || outputConfig.title,
        type: 'generated',
        status: 'draft',
        vaultPath,
        metadata: assetMetadata,
        createdBy: input.userId,
      } as never)
      .returning() as unknown as AssetRow[]
    if (!asset) throw new Error(`Generated ${generatedMediaLabel(input.generationType)} asset was not created`)

    let version: AssetVersionRow | undefined
    try {
      await input.recheck?.()
      ;[version] = await db
        .insert(assetVersions)
        .values({
          assetId: asset.id,
          workspaceId: input.workspaceId,
          version: 1,
          r2Key,
          metadata: {
            ...assetMetadata,
            fileName,
          },
          createdBy: input.userId,
        } as never)
        .returning() as unknown as AssetVersionRow[]

      await input.recheck?.()
      await bucket.put(r2Key, input.bytes, {
        httpMetadata: { contentType: input.mimeType },
        customMetadata: {
          workspaceId: input.workspaceId,
          source: 'studio-generate',
          generationType: input.generationType,
          model: input.model ?? '',
        },
      })
    } catch (err) {
      await cleanupGeneratedAssetRecords(asset.id, version?.id)
      throw err
    }

    if (!version) throw new Error(`Generated ${generatedMediaLabel(input.generationType)} asset version was not created`)

    return {
      url: `/api/workspaces/${input.workspaceId}/asset-versions/${version.id}/file`,
      assetId: asset.id,
      assetVersionId: version.id,
      vaultPath,
      r2Key,
      mimeType: input.mimeType,
      sizeBytes,
    }
  }

  /**
   * Fetch a provider result and store it. A result already stored for the
   * same provider job is returned instead of fetched again.
   */
  async function persistGeneratedMediaFromUrl(input: {
    context: Context
    workspaceId: string
    userId: string
    generationType: GeneratedMediaType
    prompt: string
    model: string | null
    outputPath: string | null | undefined
    sourceUrl: string
    // Authorization header for router-proxied sources. When set, the URL must target the
    // operator-configured router origin (enforced below) — the public-URL guard is replaced
    // by that origin pin, never silently dropped.
    sourceAuthorization?: string
    signal?: AbortSignal
    metadata?: Record<string, unknown>
    recheck?: () => Promise<void>
  }): Promise<PersistedGeneratedMedia> {
    const url = input.sourceAuthorization
      ? config.validateRouterSourceUrl(input.sourceUrl)
      : validateGeneratedMediaSourceUrl(input.sourceUrl, input.generationType)
    const providerJobId = stringValue(input.metadata?.providerJobId)
    if (providerJobId) {
      const existing = await findPersistedGeneratedMediaByProviderJob({
        workspaceId: input.workspaceId,
        generationType: input.generationType,
        providerJobId,
      })
      if (existing) return existing
    }

    await input.recheck?.()
    const response = await fetch(url, {
      signal: input.signal,
      ...(input.sourceAuthorization
        ? { headers: config.routerSourceHeaders?.(input.sourceAuthorization) ?? { Authorization: input.sourceAuthorization } }
        : {}),
    })
    if (!response.ok) {
      throw new Error(`Could not fetch generated ${generatedMediaLabel(input.generationType)}: ${response.status} ${response.statusText}`)
    }
    const bytes = new Uint8Array(await response.arrayBuffer())
    await input.recheck?.()
    const mimeType = response.headers.get('Content-Type')?.split(';')[0]?.trim()
      || generatedMimeTypeFromUrl(url, input.generationType)
      || GENERATED_OUTPUT_CONFIG[input.generationType].defaultMimeType
    return persistGeneratedMediaAsset({
      context: input.context,
      workspaceId: input.workspaceId,
      userId: input.userId,
      generationType: input.generationType,
      prompt: input.prompt,
      model: input.model,
      outputPath: input.outputPath,
      bytes,
      mimeType,
      extension: generatedExtensionFromUrl(url, input.generationType) ?? extensionForGeneratedMimeType(input.generationType, mimeType),
      metadata: {
        providerResultUrl: url,
        ...input.metadata,
      },
      recheck: input.recheck,
    })
  }

  /** Best-effort removal of a stored result that its generation did not keep. */
  async function cleanupGeneratedMediaAsset(context: Context, media: {
    assetId: string
    assetVersionId: string
    r2Key: string
  }): Promise<void> {
    const bucket = config.bucket(context)
    if (bucket) {
      await bucket.delete(media.r2Key).catch((err) => {
        console.error('Generated media file cleanup failed:', err instanceof Error ? err.message : String(err))
      })
    }
    await cleanupGeneratedAssetRecords(media.assetId, media.assetVersionId).catch((err) => {
      console.error('Generated media record cleanup failed:', err instanceof Error ? err.message : String(err))
    })
  }

  async function writeGeneratedTranscriptVaultFile(input: {
    workspaceId: string
    generationId: string
    prompt: string
    model: string | null
    outputPath: string | null | undefined
    transcript: string
    sourceAudioUrl: string
    language?: string
    responseFormat?: string
    createdAt: Date
    status: string
  }): Promise<{ vaultPath: string }> {
    const id = crypto.randomUUID()
    const fileName = `studio-${id}.md`
    const vaultPath = resolveGeneratedVaultPath({
      type: 'transcription',
      outputPath: input.outputPath,
      fileName,
    })
    await config.writeVaultFile(input.workspaceId, vaultPath, {
      frontmatter: {
        type: GENERATED_OUTPUT_CONFIG.transcription.frontmatterType,
        generationId: input.generationId,
        sourceAudioUrl: input.sourceAudioUrl,
        prompt: input.prompt,
        model: input.model ?? '',
        language: input.language ?? '',
        responseFormat: input.responseFormat ?? '',
        status: input.status,
        created: input.createdAt.toISOString(),
      },
      body: input.transcript,
    })
    return { vaultPath }
  }

  return { persistGeneratedMediaAsset, persistGeneratedMediaFromUrl, cleanupGeneratedMediaAsset, writeGeneratedTranscriptVaultFile }
}

/** Deletion of generated media rows and their bucket objects. */
function createGeneratedMediaDeletes<Context>(config: GeneratedMediaStoreConfig<Context>, queries: GeneratedMediaQueries) {
  const { db } = config
  const { assets, assetVersions, generations } = config.tables

  const { listGeneratedAssetVersionRows, readGeneratedMediaVaultEntryByPath } = queries

  /**
   * Delete the studio-generated media entry at a vault path: the `asset` row,
   * every `asset_version` row under it, and every `generation` row that points
   * at one of those versions, so no generation keeps advertising bytes that are
   * gone. Rows go in one batch; the bucket objects are deleted last.
   */
  async function deleteGeneratedMediaAsset(input: {
    bucket: GeneratedMediaBucket
    workspaceId: string
    path: string
    expectedRevision: string
  }): Promise<DeleteGeneratedMediaResult> {
    validateVaultFilePath(input.path)
    const entry = await readGeneratedMediaVaultEntryByPath(input.workspaceId, input.path, { visibleOnly: false })
    if (!entry) return { ok: false, reason: 'not_found' }
    if (entry.file.revision !== input.expectedRevision) return { ok: false, reason: 'revision_mismatch' }

    await deleteGeneratedAssetRows({
      bucket: input.bucket,
      workspaceId: input.workspaceId,
      assetIds: [entry.file.metadata.assetId],
      generationIds: [],
    })
    return { ok: true }
  }

  /**
   * Delete studio-generated media addressed by `generation` id. Ids with no
   * row in this workspace are skipped rather than reported, so a repeated
   * batch is a no-op; `deleted` counts the requested rows that were there.
   */
  async function deleteGeneratedMediaByGenerationIds(input: {
    bucket: GeneratedMediaBucket | null
    workspaceId: string
    ids: string[]
  }): Promise<{ deleted: number }> {
    const rows = await inIdChunks(input.ids, (batch) => db
      .select({ id: generations.id, metadata: generations.metadata })
      .from(generations)
      .where(and(
        eq(generations.workspaceId, input.workspaceId),
        inArray(generations.id, batch),
      )) as unknown as PromiseLike<Array<{ id: string; metadata: unknown }>>)
    if (rows.length === 0) return { deleted: 0 }

    const assetVersionIds = [...new Set(rows
      .map((row) => stringValue(metadataRecord(row.metadata).assetVersionId))
      .filter((id): id is string => Boolean(id)))]
    const versionRows = assetVersionIds.length === 0
      ? []
      : await listGeneratedAssetVersionRows(input.workspaceId, assetVersionIds, { visibleOnly: false })
    const assetIds = [...new Set(versionRows
      .filter((row) => row.asset.type === 'generated')
      .map((row) => row.asset.id))]

    await deleteGeneratedAssetRows({
      bucket: input.bucket,
      workspaceId: input.workspaceId,
      assetIds,
      generationIds: rows.map((row) => row.id),
    })
    return { deleted: rows.length }
  }

  /** Row and object removal shared by both delete entry points. Every
   *  `generation` row linked to a version of `assetIds` joins the delete set:
   *  provider-job dedupe lets several generations share one asset version. */
  async function deleteGeneratedAssetRows(input: {
    bucket: GeneratedMediaBucket | null
    workspaceId: string
    assetIds: string[]
    generationIds: string[]
  }): Promise<void> {
    const versionRows = input.assetIds.length === 0
      ? []
      : await inIdChunks(input.assetIds, (batch) => db
        .select({ id: assetVersions.id, r2Key: assetVersions.r2Key })
        .from(assetVersions)
        .where(and(
          eq(assetVersions.workspaceId, input.workspaceId),
          inArray(assetVersions.assetId, batch),
        )) as unknown as PromiseLike<Array<{ id: string; r2Key: string | null }>>)

    const linkedGenerations = versionRows.length === 0
      ? []
      : await inIdChunks(versionRows.map((row) => row.id), (batch) => db
        .select({ id: generations.id })
        .from(generations)
        .where(and(
          eq(generations.workspaceId, input.workspaceId),
          inArray(sql`json_extract(${generations.metadata}, '$.assetVersionId')`, batch),
        )) as unknown as PromiseLike<Array<{ id: string }>>)

    const generationIds = [...new Set([...input.generationIds, ...linkedGenerations.map((row) => row.id)])]
    if (generationIds.length === 0 && input.assetIds.length === 0) return

    const deleteGenerations = db.delete(generations).where(and(
      eq(generations.workspaceId, input.workspaceId),
      inArray(generations.id, generationIds),
    ))
    if (input.assetIds.length === 0) {
      await db.batch([deleteGenerations])
    } else {
      await db.batch([
        db.delete(assetVersions).where(and(
          eq(assetVersions.workspaceId, input.workspaceId),
          inArray(assetVersions.assetId, input.assetIds),
        )),
        db.delete(assets).where(and(
          eq(assets.workspaceId, input.workspaceId),
          inArray(assets.id, input.assetIds),
        )),
        deleteGenerations,
      ])
    }

    if (!input.bucket) return
    for (const row of versionRows) {
      if (!row.r2Key) continue
      const r2Key = row.r2Key
      await input.bucket.delete(r2Key).catch((err) => {
        console.error('Generated media R2 object cleanup failed:', r2Key, err instanceof Error ? err.message : String(err))
      })
    }
  }

  return { deleteGeneratedMediaAsset, deleteGeneratedMediaByGenerationIds }
}

/** Create the generated-media store over a product's tables. */
export function createGeneratedMediaStore<Context>(config: GeneratedMediaStoreConfig<Context>) {
  const queries = createGeneratedMediaQueries(config)
  const { listGeneratedMediaVaultPaths, listGeneratedMediaVaultEntries, readGeneratedMediaVaultFile } = queries
  return {
    tables: config.tables,
    ...createGeneratedMediaWrites(config, queries),
    ...createGeneratedMediaDeletes(config, queries),
    listGeneratedMediaVaultPaths,
    listGeneratedMediaVaultEntries,
    readGeneratedMediaVaultFile,
  }
}


function buildGeneratedMediaVaultEntry(
  workspaceId: string,
  generation: GenerationRow,
  row: GeneratedAssetVersionRow,
): GeneratedMediaVaultEntry | null {
  const generationMetadata = metadataRecord(generation.metadata)
  const assetVersionId = stringValue(generationMetadata.assetVersionId) ?? row.version.id
  const assetMetadata = metadataRecord(row.asset.metadata)
  const versionMetadata = metadataRecord(row.version.metadata)
  const generationType = stringValue(versionMetadata.generationType) ?? stringValue(assetMetadata.generationType)
  if (!isGeneratedMediaType(generationType) || generationType !== generation.type) return null

  const fileName = stringValue(versionMetadata.fileName)
  if (!fileName) return null

  const blobUrl = stringValue(generation.result) ?? `/api/workspaces/${workspaceId}/asset-versions/${assetVersionId}/file`
  const mimeType = stringValue(versionMetadata.mimeType) ?? stringValue(assetMetadata.mimeType) ?? GENERATED_OUTPUT_CONFIG[generationType].defaultMimeType
  const path = stringValue(row.asset.vaultPath)
    ?? stringValue(generationMetadata.vaultPath)
    ?? resolveGeneratedVaultPath({
      type: generationType,
      outputPath: stringValue(generationMetadata.outputPath),
      fileName,
    })
  validateVaultFilePath(path)

  return {
    path,
    file: {
      kind: 'media',
      path,
      content: '',
      frontmatter: {
        type: GENERATED_OUTPUT_CONFIG[generationType].frontmatterType,
        prompt: generation.prompt,
        model: generation.model ?? '',
        status: stringValue(generationMetadata.generationStatus) ?? 'unknown',
        providerStatus: stringValue(generationMetadata.providerStatus) ?? '',
        providerJobId: stringValue(generationMetadata.providerJobId) ?? '',
        assetId: row.asset.id,
        assetVersionId,
        created: generation.createdAt.toISOString(),
      },
      body: '',
      blobUrl,
      mimeType,
      revision: row.version.id,
      metadata: {
        prompt: generation.prompt,
        model: generation.model,
        createdAt: generation.createdAt,
        generationStatus: stringValue(generationMetadata.generationStatus) ?? 'unknown',
        providerStatus: stringValue(generationMetadata.providerStatus),
        providerJobId: stringValue(generationMetadata.providerJobId),
        assetId: row.asset.id,
        assetVersionId,
        fileName,
        sizeBytes: numberValue(versionMetadata.sizeBytes) ?? numberValue(assetMetadata.sizeBytes),
      },
    },
  }
}

function persistedGeneratedMediaFromRow(workspaceId: string, row: GeneratedAssetVersionRow): PersistedGeneratedMedia {
  const versionMetadata = metadataRecord(row.version.metadata)
  const r2Key = stringValue(row.version.r2Key)
  const vaultPath = stringValue(row.asset.vaultPath)
  const mimeType = stringValue(versionMetadata.mimeType)
  const sizeBytes = numberValue(versionMetadata.sizeBytes)
  if (!r2Key || !vaultPath || !mimeType || sizeBytes == null) {
    throw new Error(GENERATED_MEDIA_MISSING_FILE_METADATA)
  }
  validateVaultFilePath(vaultPath)
  return {
    url: `/api/workspaces/${workspaceId}/asset-versions/${row.version.id}/file`,
    assetId: row.asset.id,
    assetVersionId: row.version.id,
    vaultPath,
    r2Key,
    mimeType,
    sizeBytes,
  }
}

