import { chromium } from 'playwright'
import { mkdir } from 'node:fs/promises'

const media = '/tmp/agent-app1583-proof/media'
await mkdir(media, { recursive: true })
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] })
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1, recordVideo: { dir: media, size: { width: 1440, height: 900 } } })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.goto('http://127.0.0.1:4175/before', { waitUntil: 'networkidle' })
await page.screenshot({ path: `${media}/before-desktop.png`, fullPage: true })
await page.waitForTimeout(900)
await page.goto('http://127.0.0.1:4175/after', { waitUntil: 'networkidle' })
await page.getByText('Cloudbeds').first().waitFor()
await page.screenshot({ path: `${media}/after-catalog-desktop.png`, fullPage: true })
await page.waitForTimeout(900)
await page.getByLabel('Account for Cloudbeds').selectOption('hotel-b')
await page.getByText('Update a room').waitFor()
if (!page.url().includes('connection=hotel-b')) throw new Error('Selection did not persist in URL')
await page.screenshot({ path: `${media}/after-detail-desktop.png`, fullPage: true })
await page.waitForTimeout(900)
await page.getByLabel('Decision for cloudbeds.rooms.update').selectOption('ask')
await page.getByText('Permission saved and verified.').waitFor()
const decision = await page.getByLabel('Decision for cloudbeds.rooms.update').inputValue()
if (decision !== 'ask') throw new Error(`Policy was not reconciled: ${decision}`)
const calls = await page.evaluate(() => window.__hubProof.calls)
if (!calls.some(value => value === 'PUT /api/hub/settings/policies')) throw new Error('No policy write')
if (calls.filter(value => value === 'GET /api/hub/settings/policies?connectionId=hotel-b').length < 2) throw new Error('No authoritative policy reread')
await page.screenshot({ path: `${media}/after-policy-desktop.png`, fullPage: true })
await page.waitForTimeout(900)
await page.reload({ waitUntil: 'networkidle' })
await page.getByText('Update a room').waitFor()
if (await page.getByLabel('Account for Cloudbeds').inputValue() !== 'hotel-b') throw new Error('Account selection did not survive reload')
if (await page.getByLabel('Decision for cloudbeds.rooms.update').inputValue() !== 'ask') throw new Error('Stored policy did not survive fixture reload')
await page.waitForTimeout(900)
await page.getByRole('button', { name: 'Connect another account' }).click()
await page.getByRole('textbox', { name: 'API key' }).waitFor()
await page.screenshot({ path: `${media}/after-connect-dialog-desktop.png`, fullPage: true })
await page.waitForTimeout(900)
await page.getByRole('textbox', { name: 'API key' }).fill('fixture-key')
await page.getByRole('button', { name: /^Connect$/ }).click()
await page.getByText('Connection saved and verified.').waitFor()
await page.getByLabel('Account for Cloudbeds').selectOption('hotel-c')
if (await page.getByLabel('Account for Cloudbeds').inputValue() !== 'hotel-c') throw new Error('New account was not selectable')
await page.locator('[data-testid="integration-connection-detail"]').getByText('Hotel C', { exact: true }).waitFor()
await page.screenshot({ path: `${media}/after-added-account-desktop.png`, fullPage: true })
await page.waitForTimeout(900)
const overflowDesktop = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
await context.close()

const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 })
const mobilePage = await phone.newPage()
mobilePage.on('pageerror', error => errors.push(error.message))
await mobilePage.goto('http://127.0.0.1:4175/before', { waitUntil: 'networkidle' })
await mobilePage.screenshot({ path: `${media}/before-phone.png`, fullPage: true })
await mobilePage.goto('http://127.0.0.1:4175/after', { waitUntil: 'networkidle' })
await mobilePage.getByText('Cloudbeds').first().waitFor()
await mobilePage.screenshot({ path: `${media}/after-catalog-phone.png`, fullPage: true })
await mobilePage.getByLabel('Account for Cloudbeds').selectOption('hotel-a')
await mobilePage.getByText('Update a room').waitFor()
await mobilePage.screenshot({ path: `${media}/after-detail-phone.png`, fullPage: true })
const overflowPhone = await mobilePage.evaluate(() => document.documentElement.scrollWidth > innerWidth)
await phone.close()
await browser.close()
if (errors.length) throw new Error(`Browser errors: ${errors.join(' | ')}`)
if (overflowDesktop || overflowPhone) throw new Error(`Horizontal overflow desktop=${overflowDesktop} phone=${overflowPhone}`)
console.log(JSON.stringify({ consumer: 'packed agent-app 0.50.30 candidate', target: 'Chromium 1440x900 and 390x844', selected: 'hotel-b', decision: 'ask', policyWrite: true, policyReread: true, reloadSelection: true, apiKeyConnection: true, horizontalOverflow: false, browserErrors: 0, media }, null, 2))
